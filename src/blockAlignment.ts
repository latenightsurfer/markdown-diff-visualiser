/**
 * Block Alignment - Extends line-based diff blocks to the boundaries of the enclosing markdown
 * blocks, so that a table, list, blockquote or fenced code block is never split into fragments
 * that markdown-it can no longer recognise (issue #9).
 */

import type { BlockDiff } from './diffHighlighter';
import type { LineRange } from './markdownRenderer';

const WHITESPACE_RUN = /\s+/g;
/** The number of an ordered list item at the start of a trimmed line, e.g. `12.` or `3)`. */
const ORDERED_LIST_NUMBER = /^\d+([.)]) /;

export interface AlignedBlock extends BlockDiff {
  /** 0-based indices into `oldLines` of the lines that were removed or modified. */
  readonly changedOldLines: readonly number[];
  /** 0-based indices into `newLines` of the lines that were added or modified. */
  readonly changedNewLines: readonly number[];
}

/**
 * Merge consecutive diff blocks until every split point lies between two top-level markdown
 * blocks on both the old and the new side. Unchanged lines join a changed markdown block only
 * as far as that block reaches; the remaining unchanged lines stay unchanged.
 *
 * @param blocks line-based blocks covering both documents in order (from `computeBlockDiffs`)
 * @param oldRanges top-level block ranges of the old document
 * @param newRanges top-level block ranges of the new document
 */
export function alignToMarkdownBlocks(
  blocks: readonly BlockDiff[],
  oldRanges: readonly LineRange[],
  newRanges: readonly LineRange[],
): AlignedBlock[] {
  const lineBlocks = blocks.flatMap(splitUnchangedLines);
  const groups = groupAtBlockBoundaries(lineBlocks, oldRanges, newRanges);
  return joinAdjacentUnchanged(groups.map(mergeBlocks));
}

/**
 * Split an unchanged block into one block per line, so it can be divided at any boundary.
 */
function splitUnchangedLines(block: BlockDiff): BlockDiff[] {
  if (block.type !== 'unchanged') {
    return [block];
  }
  const lineCount = Math.max(block.oldLines.length, block.newLines.length);
  return lineIndices(0, lineCount).map((index) => ({
    type: 'unchanged',
    oldLines: block.oldLines.slice(index, index + 1),
    newLines: block.newLines.slice(index, index + 1),
  }));
}

function groupAtBlockBoundaries(
  blocks: readonly BlockDiff[],
  oldRanges: readonly LineRange[],
  newRanges: readonly LineRange[],
): BlockDiff[][] {
  const groups: BlockDiff[][] = [];
  let group: BlockDiff[] = [];
  let oldOffset = 0;
  let newOffset = 0;

  for (const block of blocks) {
    group.push(block);
    oldOffset += block.oldLines.length;
    newOffset += block.newLines.length;
    if (isBlockBoundary(oldOffset, oldRanges) && isBlockBoundary(newOffset, newRanges)) {
      groups.push(group);
      group = [];
    }
  }
  if (group.length > 0) {
    groups.push(group);
  }
  return groups;
}

/**
 * Join neighbouring unchanged blocks again, so unchanged content is rendered in one piece.
 */
function joinAdjacentUnchanged(blocks: readonly AlignedBlock[]): AlignedBlock[] {
  const joined: AlignedBlock[] = [];
  for (const block of blocks) {
    const previous = joined[joined.length - 1];
    if (previous?.type === 'unchanged' && block.type === 'unchanged') {
      joined[joined.length - 1] = mergeBlocks([previous, block]);
    } else {
      joined.push(block);
    }
  }
  return joined;
}

/**
 * A line offset is a block boundary if no markdown block starts before it and ends after it.
 */
function isBlockBoundary(lineOffset: number, ranges: readonly LineRange[]): boolean {
  return !ranges.some((range) => range.start < lineOffset && lineOffset < range.end);
}

function mergeBlocks(group: readonly BlockDiff[]): AlignedBlock {
  const oldLines: string[] = [];
  const newLines: string[] = [];
  const changedOldLines: number[] = [];
  const changedNewLines: number[] = [];

  for (const block of group) {
    if (block.type !== 'unchanged') {
      changedOldLines.push(...changedLineIndices(block.oldLines, block.newLines, oldLines.length));
      changedNewLines.push(...changedLineIndices(block.newLines, block.oldLines, newLines.length));
    }
    oldLines.push(...block.oldLines);
    newLines.push(...block.newLines);
  }

  const hasChanges = changedOldLines.length > 0 || changedNewLines.length > 0;
  const type = hasChanges ? changedType(oldLines.length, newLines.length) : 'unchanged';
  return { type, oldLines, newLines, changedOldLines, changedNewLines };
}

/**
 * Indices (shifted by `offset`) of the lines that have no counterpart on the other side of the
 * same diff block. Lines whose rendered output cannot differ count as unchanged: table rows
 * re-padded by a formatter after a column got wider, and list items renumbered after an item
 * was inserted (the numbers are generated by the ordered list).
 */
function changedLineIndices(
  lines: readonly string[],
  counterpart: readonly string[],
  offset: number,
): number[] {
  const counterpartKeys = new Set(counterpart.map(comparisonKey));
  return lines.flatMap((line, index) =>
    counterpartKeys.has(comparisonKey(line)) ? [] : [offset + index],
  );
}

function comparisonKey(line: string): string {
  return line.replace(WHITESPACE_RUN, ' ').trim().replace(ORDERED_LIST_NUMBER, '#$1');
}

function changedType(oldCount: number, newCount: number): BlockDiff['type'] {
  if (oldCount > 0 && newCount > 0) {
    return 'modified';
  }
  return newCount > 0 ? 'added' : 'removed';
}

function lineIndices(start: number, count: number): number[] {
  return Array.from({ length: count }, (_, index) => start + index);
}
